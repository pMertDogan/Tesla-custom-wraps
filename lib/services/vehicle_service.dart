  /// Every vehicle Tesla publishes a wrap template for.
  static List<TeslaModel> getVehicles() => List.unmodifiable(_vehicles);

  /// Looks a vehicle up by its [TeslaModel.id].
  ///
  /// Returns `null` when no vehicle matches.
  static TeslaModel? findById(String id) {
    for (final vehicle in _vehicles) {
      if (vehicle.id == id) return vehicle;
    }
    return null;
  }

  /// Flat list of every example wrap shipped by Tesla.
  static List<String> get allExampleWrapPaths => [
    for (final vehicle in _vehicles) ...vehicle.exampleWraps,
  ];
}
